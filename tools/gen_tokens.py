#!/usr/bin/env python3
"""tokens.json -> app/tokens.css (Tailwind v4 @theme) + preview/tokens.css (:root mirror) + preview/tokens.html

单一事实源是 content/design/tokens.json。产物头部带「勿手改」。
用法：
  python3 tools/gen_tokens.py           # 生成/覆盖
  python3 tools/gen_tokens.py --check   # 只校验，不同步则退出码 1
"""
from __future__ import annotations

import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "content" / "design" / "tokens.json"
OUT_THEME = ROOT / "app" / "tokens.css"
OUT_PREVIEW_CSS = ROOT / "preview" / "tokens.css"
OUT_PREVIEW_HTML = ROOT / "preview" / "tokens.html"

HEADER = "/* GENERATED by tools/gen_tokens.py — 勿手改，改 content/design/tokens.json */\n"


def load() -> dict:
    return json.loads(TOKENS.read_text(encoding="utf-8"))


def build_theme(t: dict) -> str:
    lines = [HEADER, "@theme static {\n"]
    for k, v in t["color"].items():
        lines.append(f"  --color-{k}: {v};\n")
    for k, v in t["font"].items():
        lines.append(f"  --font-{k}: {v};\n")
    for k, v in t["fontSize"].items():
        lines.append(f"  --text-{k}: {v['size']};\n")
        lines.append(f"  --text-{k}--line-height: {v['lineHeight']};\n")
        lines.append(f"  --text-{k}--letter-spacing: {v['letterSpacing']};\n")
        lines.append(f"  --text-{k}--font-weight: {v['weight']};\n")
    for k, v in t["radius"].items():
        lines.append(f"  --radius-{k}: {v};\n")
    for k, v in t["spacing"].items():
        lines.append(f"  --spacing-{k}: {v};\n")
    for k, v in t["shadow"].items():
        lines.append(f"  --shadow-{k}: {v};\n")
    for k, v in t["layout"].items():
        lines.append(f"  --layout-{k}: {v};\n")
    lines.append("}\n")
    return "".join(lines)


def build_preview_css(t: dict) -> str:
    lines = [HEADER, ":root {\n"]
    for k, v in t["color"].items():
        lines.append(f"  --color-{k}: {v};\n")
    for k, v in t["font"].items():
        lines.append(f"  --font-{k}: {v};\n")
    for k, v in t["fontSize"].items():
        lines.append(f"  --text-{k}: {v['size']};\n")
        lines.append(f"  --text-{k}--line-height: {v['lineHeight']};\n")
    for k, v in t["radius"].items():
        lines.append(f"  --radius-{k}: {v};\n")
    for k, v in t["spacing"].items():
        lines.append(f"  --spacing-{k}: {v};\n")
    for k, v in t["layout"].items():
        lines.append(f"  --layout-{k}: {v};\n")
    lines.append("}\n")
    return "".join(lines)


def build_preview_html(t: dict) -> str:
    swatches = "".join(
        f'<div class="sw"><div class="chip" style="background:{html.escape(v)}"></div>'
        f'<code>{html.escape(k)}</code><span>{html.escape(v)}</span></div>'
        for k, v in t["color"].items()
    )
    type_rows = "".join(
        f'<div class="tr"><code>text-{html.escape(k)}</code>'
        f'<span style="font-family:var(--font-{ "serif" if "headline" in k or "display" in k or k == "seal" else "sans" });'
        f'font-size:{html.escape(v["size"])};line-height:{html.escape(v["lineHeight"])};'
        f'font-weight:{html.escape(v["weight"])};letter-spacing:{html.escape(v["letterSpacing"])}">'
        f'中外千载 · 双轨平行编年史策 BC 221 — AD 1840</span></div>'
        for k, v in t["fontSize"].items()
    )
    return f"""<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8"><title>历策时空 · 令牌预览</title>
<link rel="stylesheet" href="./tokens.css">
<style>
body{{background:var(--color-canvas);color:var(--color-ink);font-family:var(--font-sans);padding:var(--spacing-2xl);margin:0}}
h1{{font-family:var(--font-serif);font-size:var(--text-headline-lg);letter-spacing:.02em;margin:0 0 .5rem}}
p.sub{{color:var(--color-ink-muted);font-size:var(--text-body-sm);margin:0 0 2rem}}
h2{{font-family:var(--font-serif);font-size:var(--text-headline-sm);margin:2.5rem 0 1rem;border-bottom:1px solid var(--color-line);padding-bottom:.5rem}}
.grid{{display:grid;grid-template-columns:repeat(auto-fill,minmax(11rem,1fr));gap:.75rem}}
.sw{{background:var(--color-surface);border:1px solid var(--color-line);border-radius:var(--radius-xs);padding:.5rem;font-size:var(--text-label-sm)}}
.chip{{height:2.5rem;border-radius:var(--radius-sm);border:1px solid var(--color-line);margin-bottom:.4rem}}
.sw code{{display:block;font-size:.7rem;color:var(--color-ink)}}
.sw span{{color:var(--color-ink-muted);font-family:ui-monospace,monospace;font-size:.68rem}}
.tr{{border-bottom:1px solid var(--color-line);padding:.6rem 0}}
.tr code{{color:var(--color-vermilion);font-size:.72rem;margin-right:1rem}}
</style></head><body>
<h1>历策时空 · 设计令牌</h1>
<p class="sub">来源 {html.escape(t["meta"]["source"])} · 生成时间由构建脚本决定 · 共 {len(t["color"])} 色 / {len(t["fontSize"])} 字阶</p>
<h2>色彩</h2><div class="grid">{swatches}</div>
<h2>字阶</h2>{type_rows}
<h2>圆角</h2><div class="grid">{"".join(f'<div class="sw"><div class="chip" style="border-radius:{html.escape(v)};background:var(--color-surface-sunken)"></div><code>radius-{html.escape(k)}</code><span>{html.escape(v)}</span></div>' for k, v in t["radius"].items())}</div>
<h2>间距</h2><div class="grid">{"".join(f'<div class="sw"><div class="chip" style="width:{html.escape(v)};background:var(--color-vermilion)"></div><code>spacing-{html.escape(k)}</code><span>{html.escape(v)}</span></div>' for k, v in t["spacing"].items())}</div>
</body></html>
"""


def main() -> int:
    t = load()
    outputs = {
        OUT_THEME: build_theme(t),
        OUT_PREVIEW_CSS: build_preview_css(t),
        OUT_PREVIEW_HTML: build_preview_html(t),
    }
    check = "--check" in sys.argv
    drift = []
    for path, content in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if check:
        if drift:
            print("令牌产物与 tokens.json 不同步：", ", ".join(drift))
            return 1
        print("令牌产物同步 ✅")
        return 0
    print("已生成：", ", ".join(str(p.relative_to(ROOT)) for p in outputs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
